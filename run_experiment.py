"""
Run Placeholder Experiment
===========================
Executes the placeholder experiment, generates a report, saves metrics to
results/RESULTS.md, and produces a summary visualisation saved to
results/placeholder_report.png.

Usage
-----
    python run_experiment.py
"""

from __future__ import annotations

import json
import os
import datetime
from pathlib import Path

import matplotlib
matplotlib.use("Agg")  # non-interactive backend
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches

from placeholder_experiment.experiment import (
    PlaceholderExperiment,
    ExperimentStatus,
    generate_placeholder_report,
)


RESULTS_DIR = Path(__file__).parent / "results"


def save_results_markdown(report: dict, output_path: Path) -> None:
    """Save experiment report metrics to a Markdown file.

    Parameters
    ----------
    report : dict
        The experiment report dictionary produced by PlaceholderExperiment.
    output_path : Path
        Destination path for the Markdown file.
    """
    validation = report["validation"]
    metadata = report["metadata"]

    lines = [
        "# Experiment Results",
        "",
        f"**Generated:** {report['timestamp']}",
        "",
        "---",
        "",
        "## Experiment Summary",
        "",
        f"| Field | Value |",
        f"|---|---|",
        f"| Experiment ID | `{report['experiment_id']}` |",
        f"| Title | {report['title']} |",
        f"| Status | `{report['status']}` |",
        f"| Submitted Document | {report['submitted_document']} |",
        f"| Document Type | {validation['document_type']} |",
        f"| Valid Paper | {'✅ Yes' if validation['is_valid'] else '❌ No'} |",
        "",
        "---",
        "",
        "## Validation Results",
        "",
        f"**Is Valid Research Paper:** `{validation['is_valid']}`",
        "",
        "### Missing Required Components",
        "",
    ]

    for component in validation["missing_components"]:
        lines.append(f"- `{component}`")

    lines += [
        "",
        "### Recommendations",
        "",
    ]

    for rec in validation["recommendations"]:
        lines.append(f"- {rec}")

    lines += [
        "",
        "---",
        "",
        "## Research Objectives",
        "",
    ]

    for obj in metadata["research_objectives"]:
        lines.append(f"- {obj}")

    lines += [
        "",
        "---",
        "",
        "## Conclusion",
        "",
        "No quantitative finance experiment could be executed because the submitted",
        "document was not a valid research paper. The DataCamp Scikit-Learn Cheat Sheet",
        "contains only generic Python API snippets and lacks all required components",
        "for a quantitative finance experiment.",
        "",
        "**Action Required:** Please resubmit the correct research paper.",
        "",
        "---",
        "",
        f"*Report generated by PlaceholderExperiment v1.0 at {report['timestamp']}*",
    ]

    output_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[✓] Results saved to {output_path}")


def save_summary_visualisation(report: dict, output_path: Path) -> None:
    """Save a summary visualisation of the placeholder experiment report.

    Parameters
    ----------
    report : dict
        The experiment report dictionary.
    output_path : Path
        Destination path for the PNG image.
    """
    validation = report["validation"]
    missing = validation["missing_components"]
    total_required = len(PlaceholderExperiment.REQUIRED_PAPER_COMPONENTS)
    present = total_required - len(missing)

    fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    fig.suptitle(
        "Placeholder Experiment — No Valid Research Paper Provided",
        fontsize=13,
        fontweight="bold",
        y=1.01,
    )

    # --- Left: Completeness pie chart ---
    ax_pie = axes[0]
    sizes = [present, len(missing)]
    labels = [f"Present ({present})", f"Missing ({len(missing)})"]
    colors = ["#4CAF50", "#F44336"]
    explode = (0, 0.05)

    wedges, texts, autotexts = ax_pie.pie(
        sizes,
        labels=labels,
        colors=colors,
        explode=explode,
        autopct="%1.0f%%",
        startangle=90,
        textprops={"fontsize": 11},
    )
    ax_pie.set_title("Required Paper Components\nCompleteness", fontsize=12)

    # --- Right: Missing components bar chart ---
    ax_bar = axes[1]
    component_labels = [c.replace("_", "\n") for c in missing]
    bar_colors = ["#F44336"] * len(missing)

    bars = ax_bar.barh(
        range(len(missing)),
        [1] * len(missing),
        color=bar_colors,
        edgecolor="white",
        height=0.6,
    )
    ax_bar.set_yticks(range(len(missing)))
    ax_bar.set_yticklabels(component_labels, fontsize=9)
    ax_bar.set_xlabel("Missing (1 = absent)", fontsize=10)
    ax_bar.set_title("Missing Required Components", fontsize=12)
    ax_bar.set_xlim(0, 1.5)
    ax_bar.axvline(x=1, color="gray", linestyle="--", linewidth=0.8, alpha=0.5)

    # Add status annotation
    status_text = (
        f"Status: {report['status'].upper()}\n"
        f"Document: {report['submitted_document']}\n"
        f"Type: {validation['document_type']}"
    )
    fig.text(
        0.5,
        -0.04,
        status_text,
        ha="center",
        fontsize=9,
        color="gray",
        style="italic",
    )

    plt.tight_layout()
    fig.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"[✓] Visualisation saved to {output_path}")


def main() -> None:
    """Run the placeholder experiment and save all results."""
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    print("=" * 60)
    print("  Placeholder Experiment Runner")
    print("=" * 60)
    print(f"  Experiment ID : exp_1")
    print(f"  Document      : DataCamp Scikit-Learn Cheat Sheet")
    print("=" * 60)

    # Generate report
    report = generate_placeholder_report(
        exp_id="exp_1",
        submitted_document_name="DataCamp Scikit-Learn Cheat Sheet",
    )

    # Print summary to console
    print(f"\n[i] Status       : {report['status']}")
    print(f"[i] Valid Paper  : {report['validation']['is_valid']}")
    print(f"[i] Doc Type     : {report['validation']['document_type']}")
    print(f"[i] Missing      : {len(report['validation']['missing_components'])} components")

    # Save JSON report
    json_path = RESULTS_DIR / "report.json"
    json_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(f"\n[✓] JSON report saved to {json_path}")

    # Save Markdown results
    md_path = RESULTS_DIR / "RESULTS.md"
    save_results_markdown(report, md_path)

    # Save visualisation
    png_path = RESULTS_DIR / "placeholder_report.png"
    save_summary_visualisation(report, png_path)

    print("\n" + "=" * 60)
    print("  Experiment run complete.")
    print("  All results saved to: results/")
    print("=" * 60)


if __name__ == "__main__":
    main()
